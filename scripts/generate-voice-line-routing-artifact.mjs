import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse as parseYaml } from 'yaml'
import {
  buildVoiceLineRoutingArtifact,
} from '../src/backend/llm/voice-line-routing-artifact.ts'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '..')
const registryPath = path.join(repoRoot, '.ai/llm-config/registry/model_profiles.yaml')
const outputPath = path.join(
  repoRoot,
  'src/backend/llm/generated/voice-line-routing.generated.ts',
)

const registry = parseYaml(readFileSync(registryPath, 'utf8'))
if (!registry || typeof registry !== 'object' || !Array.isArray(registry.profiles)) {
  throw new Error('Invalid model_profiles.yaml: missing profiles array')
}

const artifact = buildVoiceLineRoutingArtifact(
  registry.profiles.map((profile) => ({
    profile_id: profile.profile_id,
    voice_line_id: profile.voice_line_id,
    intent: profile.intent,
    tier: profile.tier,
  })),
)

const fileContents = `${[
  '// Generated by scripts/generate-voice-line-routing-artifact.mjs',
  '// Source: .ai/llm-config/registry/model_profiles.yaml',
  '',
  "import type { VoiceLineRoutingArtifact } from '../voice-line-routing-artifact.js'",
  '',
  `export const GENERATED_VOICE_LINE_ROUTING: VoiceLineRoutingArtifact = ${JSON.stringify(artifact, null, 2)}`,
  '',
].join('\n')}`

mkdirSync(path.dirname(outputPath), { recursive: true })
writeFileSync(outputPath, fileContents, 'utf8')
console.log(`Wrote ${path.relative(repoRoot, outputPath)}`)
