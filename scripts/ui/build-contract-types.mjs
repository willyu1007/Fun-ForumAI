#!/usr/bin/env node
/**
 * build-contract-types.mjs
 * Generates ui/codegen/contract-types.ts from ui/contract/contract.json.
 * Single responsibility: contract -> TypeScript types generation.
 * 
 * Key: Generates ALL roles and ALL slots from contract.json (fixes previous drift).
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '../..')
const CONTRACT_PATH = resolve(ROOT, 'ui/contract/contract.json')
const OUTPUT_DIR = resolve(ROOT, 'ui/codegen')
const OUTPUT_PATH = resolve(OUTPUT_DIR, 'contract-types.ts')

function build() {
  if (!existsSync(CONTRACT_PATH)) {
    console.error(`[FAIL] Contract file not found: ${CONTRACT_PATH}`)
    process.exit(1)
  }

  const contract = JSON.parse(readFileSync(CONTRACT_PATH, 'utf-8'))
  const contractMeta = contract.meta || {}
  const roles = contract.roles || {}

  const roleNames = Object.keys(roles).sort()
  const roleUnion = roleNames.map(r => `"${r}"`).join(' | ')

  let attrsMapLines = []
  let slotsMapLines = []

  for (const roleName of roleNames) {
    const roleDef = roles[roleName]

    // Generate attrs type
    const attrs = roleDef.attrs || {}
    const attrEntries = Object.entries(attrs)
    if (attrEntries.length > 0) {
      const attrLines = attrEntries.map(([attrName, values]) => {
        const valueUnion = values.map(v => `"${v}"`).join(' | ')
        return `    ${attrName}?: ${valueUnion};`
      })
      attrsMapLines.push(`  "${roleName}": {\n${attrLines.join('\n')}\n  };`)
    } else {
      attrsMapLines.push(`  "${roleName}": Record<string, never>;`)
    }

    // Generate slots type - include ALL slots from contract
    const slots = roleDef.slots || []
    if (slots.length > 0) {
      const slotUnion = slots.map(s => `"${s}"`).join(' | ')
      slotsMapLines.push(`  "${roleName}": ${slotUnion};`)
    } else {
      slotsMapLines.push(`  "${roleName}": never;`)
    }
  }

  const ts = `/* GENERATED FILE. DO NOT EDIT BY HAND.
 * Source: ui/contract/contract.json
 * Generated by: scripts/ui/build-contract-types.mjs
 */

export type UiRole = ${roleUnion};

export interface UiRoleAttributesMap {
${attrsMapLines.join('\n')}
}

export type UiAttrsForRole<R extends UiRole> = UiRoleAttributesMap[R];

export interface UiRoleSlotsMap {
${slotsMapLines.join('\n')}
}

export type UiSlotsForRole<R extends UiRole> = UiRoleSlotsMap[R];

// Manifest for runtime validation
export const UI_ROLE_MANIFEST = ${JSON.stringify(roles, null, 2)} as const;

export const CONTRACT_META = ${JSON.stringify(contractMeta, null, 2)} as const;

export const CONTRACT_ROLES = UI_ROLE_MANIFEST;
`

  if (!existsSync(OUTPUT_DIR)) {
    mkdirSync(OUTPUT_DIR, { recursive: true })
  }

  writeFileSync(OUTPUT_PATH, ts, 'utf-8')
  console.log(`[PASS] Generated ${OUTPUT_PATH} with ${roleNames.length} roles`)
  process.exit(0)
}

build()
