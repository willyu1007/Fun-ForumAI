#!/usr/bin/env node
/**
 * build-mobile-theme.mjs
 * Generates TypeScript theme constants for React Native / Mobile consumption.
 * Single responsibility: token -> mobile theme TS generation.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '../..')
const TOKENS_PATH = resolve(ROOT, 'ui/tokens/base.json')
const THEMES_DIR = resolve(ROOT, 'ui/tokens/themes')
const OUTPUT_DIR = resolve(ROOT, 'ui/codegen')
const OUTPUT_PATH = resolve(OUTPUT_DIR, 'mobile-theme.ts')

function parseSize(value) {
  if (typeof value === 'number') return value
  if (typeof value === 'string') {
    const num = parseFloat(value)
    return isNaN(num) ? 0 : num
  }
  return 0
}

function buildMobileTheme(tokens) {
  return {
    color: {
      bg: tokens.color.bg,
      surface: tokens.color.surface,
      surfaceElevated: tokens.color.surface_elevated,
      border: tokens.color.border,
      borderSubtle: tokens.color.border_subtle,
      primary: tokens.color.primary,
      primaryHover: tokens.color.primary_hover,
      accent: tokens.color.accent,
      textPrimary: tokens.color.text_primary,
      textSecondary: tokens.color.text_secondary,
      textMuted: tokens.color.text_muted,
      success: tokens.color.success,
      warning: tokens.color.warning,
      danger: tokens.color.danger,
      focusRing: tokens.color.focus_ring,
    },
    spacing: {
      0: parseSize(tokens.space['0']),
      1: parseSize(tokens.space['1']),
      2: parseSize(tokens.space['2']),
      3: parseSize(tokens.space['3']),
      4: parseSize(tokens.space['4']),
      5: parseSize(tokens.space['5']),
      6: parseSize(tokens.space['6']),
      7: parseSize(tokens.space['7']),
      8: parseSize(tokens.space['8']),
    },
    radius: {
      sm: parseSize(tokens.radius.sm),
      md: parseSize(tokens.radius.md),
      lg: parseSize(tokens.radius.lg),
      full: parseSize(tokens.radius.full),
    },
    typography: {
      size: {
        caption: parseSize(tokens.typography.size.caption),
        body: parseSize(tokens.typography.size.body),
        bodyLg: parseSize(tokens.typography.size.body_lg),
        h3: parseSize(tokens.typography.size.h3),
        h2: parseSize(tokens.typography.size.h2),
        h1: parseSize(tokens.typography.size.h1),
      },
      lineHeight: {
        caption: parseSize(tokens.typography.line_height.caption),
        body: parseSize(tokens.typography.line_height.body),
        heading: parseSize(tokens.typography.line_height.heading),
      },
      weight: {
        regular: tokens.typography.weight.regular,
        medium: tokens.typography.weight.medium,
        semibold: tokens.typography.weight.semibold,
        bold: tokens.typography.weight.bold,
      },
    },
  }
}

function build() {
  if (!existsSync(TOKENS_PATH)) {
    console.error(`[FAIL] Token file not found: ${TOKENS_PATH}`)
    process.exit(1)
  }

  const baseTokens = JSON.parse(readFileSync(TOKENS_PATH, 'utf-8'))
  const baseMobile = buildMobileTheme(baseTokens)

  const themes = { base: baseMobile }

  if (existsSync(THEMES_DIR)) {
    const themeFiles = readdirSync(THEMES_DIR).filter(f => f.endsWith('.json'))
    for (const file of themeFiles) {
      const themePath = resolve(THEMES_DIR, file)
      const themeTokens = JSON.parse(readFileSync(themePath, 'utf-8'))
      const themeName = themeTokens.meta?.theme || file.replace('.json', '')
      const merged = { ...baseTokens, ...themeTokens, color: { ...baseTokens.color, ...themeTokens.color } }
      themes[themeName.replace('.', '_')] = buildMobileTheme(merged)
    }
  }

  const ts = `/* GENERATED FILE. DO NOT EDIT BY HAND.
 * Source: ui/tokens/base.json + ui/tokens/themes/*.json
 * Generated by: scripts/ui/build-mobile-theme.mjs
 */

export interface MobileTheme {
  color: {
    bg: string
    surface: string
    surfaceElevated: string
    border: string
    borderSubtle: string
    primary: string
    primaryHover: string
    accent: string
    textPrimary: string
    textSecondary: string
    textMuted: string
    success: string
    warning: string
    danger: string
    focusRing: string
  }
  spacing: Record<0 | 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8, number>
  radius: {
    sm: number
    md: number
    lg: number
    full: number
  }
  typography: {
    size: {
      caption: number
      body: number
      bodyLg: number
      h3: number
      h2: number
      h1: number
    }
    lineHeight: {
      caption: number
      body: number
      heading: number
    }
    weight: {
      regular: number
      medium: number
      semibold: number
      bold: number
    }
  }
}

export const MOBILE_THEMES = ${JSON.stringify(themes, null, 2)} as const

export type MobileThemeName = keyof typeof MOBILE_THEMES

// Alias for backward compatibility with existing mobile code
export const colors = MOBILE_THEMES.default_light?.color ?? MOBILE_THEMES.base.color
export const spacing = MOBILE_THEMES.default_light?.spacing ?? MOBILE_THEMES.base.spacing
export const radius = MOBILE_THEMES.default_light?.radius ?? MOBILE_THEMES.base.radius
export const typography = MOBILE_THEMES.default_light?.typography ?? MOBILE_THEMES.base.typography
`

  if (!existsSync(OUTPUT_DIR)) {
    mkdirSync(OUTPUT_DIR, { recursive: true })
  }

  writeFileSync(OUTPUT_PATH, ts, 'utf-8')
  console.log(`[PASS] Generated ${OUTPUT_PATH}`)
  process.exit(0)
}

build()
