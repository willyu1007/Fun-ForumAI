#!/usr/bin/env node
/**
 * build-tokens-css.mjs
 * Generates ui/styles/tokens.css from ui/tokens/base.json + themes.
 * Single responsibility: token -> CSS variable generation.
 * 
 * Key: Uses ACTUAL token values (navy+orange), not hardcoded blue.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '../..')
const TOKENS_PATH = resolve(ROOT, 'ui/tokens/base.json')
const THEMES_DIR = resolve(ROOT, 'ui/tokens/themes')
const OUTPUT_PATH = resolve(ROOT, 'ui/styles/tokens.css')

function flattenTokens(obj, prefix = '') {
  const result = {}
  for (const [key, value] of Object.entries(obj)) {
    const newKey = prefix ? `${prefix}-${key}` : key
    if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      Object.assign(result, flattenTokens(value, newKey))
    } else {
      result[newKey] = value
    }
  }
  return result
}

function toCssVarName(key) {
  return `--ui-${key.replace(/_/g, '-')}`
}

function formatCssValue(value) {
  if (typeof value === 'number') {
    return String(value)
  }
  return value
}

function generateCssVariables(tokens) {
  const flat = flattenTokens(tokens)
  const lines = []

  const sortedKeys = Object.keys(flat).sort()
  for (const key of sortedKeys) {
    if (key.startsWith('meta')) continue
    const varName = toCssVarName(key)
    const value = formatCssValue(flat[key])
    lines.push(`    ${varName}: ${value};`)
  }

  return lines.join('\n')
}

function generateThemeOverrides(baseTokens, themeTokens, themeName) {
  const baseFlat = flattenTokens(baseTokens)
  const themeFlat = flattenTokens(themeTokens)
  const lines = []

  const sortedKeys = Object.keys(themeFlat).sort()
  for (const key of sortedKeys) {
    if (key.startsWith('meta')) continue
    const baseValue = baseFlat[key]
    const themeValue = themeFlat[key]

    if (themeValue !== baseValue) {
      const varName = toCssVarName(key)
      const value = formatCssValue(themeValue)
      lines.push(`    ${varName}: ${value};`)
    }
  }

  return lines.length > 0 ? lines.join('\n') : null
}

function build() {
  if (!existsSync(TOKENS_PATH)) {
    console.error(`[FAIL] Token file not found: ${TOKENS_PATH}`)
    process.exit(1)
  }

  const baseTokens = JSON.parse(readFileSync(TOKENS_PATH, 'utf-8'))
  const baseVars = generateCssVariables(baseTokens)

  let css = `/* GENERATED FILE. DO NOT EDIT BY HAND.
 * Source: ui/tokens/base.json + ui/tokens/themes/*.json
 * Generated by: scripts/ui/build-tokens-css.mjs
 */
@layer tokens {
  :root {
${baseVars}
  }
`

  if (existsSync(THEMES_DIR)) {
    const themeFiles = readdirSync(THEMES_DIR).filter(f => f.endsWith('.json'))

    for (const file of themeFiles) {
      const themePath = resolve(THEMES_DIR, file)
      const themeTokens = JSON.parse(readFileSync(themePath, 'utf-8'))
      const themeName = themeTokens.meta?.theme || file.replace('.json', '')

      const overrides = generateThemeOverrides(baseTokens, themeTokens, themeName)
      if (overrides) {
        css += `
  :root[data-theme="${themeName}"] {
${overrides}
  }
`
      }
    }
  }

  css += `}
`

  writeFileSync(OUTPUT_PATH, css, 'utf-8')
  console.log(`[PASS] Generated ${OUTPUT_PATH}`)
  process.exit(0)
}

build()
