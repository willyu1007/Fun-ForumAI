#!/usr/bin/env node
/**
 * build-web-theme.mjs
 * Generates TypeScript theme constants for Web consumption.
 * Single responsibility: token -> web theme TS generation.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '../..')
const TOKENS_PATH = resolve(ROOT, 'ui/tokens/base.json')
const THEMES_DIR = resolve(ROOT, 'ui/tokens/themes')
const OUTPUT_DIR = resolve(ROOT, 'ui/codegen')
const OUTPUT_PATH = resolve(OUTPUT_DIR, 'web-theme.ts')

function build() {
  if (!existsSync(TOKENS_PATH)) {
    console.error(`[FAIL] Token file not found: ${TOKENS_PATH}`)
    process.exit(1)
  }

  const baseTokens = JSON.parse(readFileSync(TOKENS_PATH, 'utf-8'))

  const themes = {}
  if (existsSync(THEMES_DIR)) {
    const themeFiles = readdirSync(THEMES_DIR).filter(f => f.endsWith('.json'))
    for (const file of themeFiles) {
      const themePath = resolve(THEMES_DIR, file)
      const themeTokens = JSON.parse(readFileSync(themePath, 'utf-8'))
      const themeName = themeTokens.meta?.theme || file.replace('.json', '')
      themes[themeName] = { ...baseTokens, ...themeTokens, color: { ...baseTokens.color, ...themeTokens.color } }
    }
  }

  const ts = `/* GENERATED FILE. DO NOT EDIT BY HAND.
 * Source: ui/tokens/base.json + ui/tokens/themes/*.json
 * Generated by: scripts/ui/build-web-theme.mjs
 */

export const BASE_TOKENS = ${JSON.stringify(baseTokens, null, 2)} as const

export const THEMES = ${JSON.stringify(themes, null, 2)} as const

export type ThemeName = keyof typeof THEMES

export function applyTheme(theme: ThemeName) {
  document.documentElement.dataset.theme = theme
  // Short-term bridge: also toggle .dark class for shadcn compatibility
  document.documentElement.classList.toggle('dark', theme.includes('dark'))
}

export function getTheme(): ThemeName {
  return (document.documentElement.dataset.theme as ThemeName) || 'default.light'
}
`

  if (!existsSync(OUTPUT_DIR)) {
    mkdirSync(OUTPUT_DIR, { recursive: true })
  }

  writeFileSync(OUTPUT_PATH, ts, 'utf-8')
  console.log(`[PASS] Generated ${OUTPUT_PATH}`)
  process.exit(0)
}

build()
